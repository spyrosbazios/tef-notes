// The app's icons, from the SVGs in assets/logo/ (the logo's one source): `bun scripts/icons.ts` after editing them.
// Writes the launcher, themed-icon, splash and notification PNGs to assets/images/ (app.config.ts points at them) and the
// mark's outline to packages/core/src/brand.ts, the path every client's brand draws (ui/brand.tsx, web/src/components/brand.tsx,
// site/src/components/ui.tsx, the extension's toolbar icon), so each shows the very shape the launcher does.
import { Resvg } from "@resvg/resvg-js";
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const root = join(import.meta.dirname, "..");
const svg = (name: string) => readFileSync(join(root, "assets/logo", `${name}.svg`), "utf8");
const png = (source: string, size: number, out: string) => {
  const bytes = new Resvg(source, { fitTo: { mode: "width", value: size } }).render().asPng();
  if (bytes.length > 500_000) throw new Error(`${out} is ${bytes.length} bytes`);
  writeFileSync(join(root, "assets/images", out), bytes);
};

/** The mark's bounds in the 1024 canvas, padded: the notification icon fills its box (Android draws it at 24 dp). */
const MARK_BOX = "194 194 636 636";

png(svg("logo"), 1024, "icon.png");
png(svg("foreground"), 1024, "android-icon-foreground.png");
png(svg("monochrome"), 1024, "android-icon-monochrome.png");
// Android's splash draws the image on a 288 dp canvas, so the mark keeps its place inside the central 66% (xxxhdpi: 1152 px)
png(svg("foreground"), 1152, "splash-icon.png");
png(svg("monochrome").replace('viewBox="0 0 1024 1024"', `viewBox="${MARK_BOX}"`), 96, "notification-icon.png");

const path = /<path id="mark"[^>]* d="([^"]+)"/.exec(svg("foreground"))?.[1];
if (!path) throw new Error("assets/logo/foreground.svg has no #mark path");
writeFileSync(
  join(root, "../packages/core/src/brand.ts"),
  `// Generated by mobile/scripts/icons.ts from mobile/assets/logo/foreground.svg: never edit.\n` +
    `/** The mark's outline (even-odd) in a 1024 canvas, and the square of it that frames the mark for an in-app icon. */\n` +
    `export const MARK_PATH = "${path}";\nexport const MARK_VIEWBOX = "${MARK_BOX}";\n\n` +
    `/** The mark as a standalone SVG document in \`fill\`: what rasterises it (the extension's toolbar icons). */\n` +
    `export const markSvg = (fill: string) =>\n` +
    `  \`<svg xmlns="http://www.w3.org/2000/svg" viewBox="\${MARK_VIEWBOX}"><path d="\${MARK_PATH}" fill="\${fill}" fill-rule="evenodd"/></svg>\`;\n`,
);
console.log("icons: assets/images/*.png and packages/core/src/brand.ts written");
