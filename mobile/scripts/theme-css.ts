// Writes src/theme.css (gitignored) from packages/core/src/theme.ts: one Uniwind theme per palette, each a `@variant <name>`
// block setting the app's colours (`bg-bg`, `text-dim`, `bg-accent`...), so a class follows `Uniwind.setTheme`.
// global.css imports it; `pages` runs this before Metro and tsc.
// The utilities are declared once in `@theme` (the default's values); Uniwind refuses a build where one theme lacks
// a variable another has, and every theme here sets the same names, the palette's and its tints'.
import { writeFileSync } from "node:fs";
import { DEFAULT_THEME, THEME_NAMES, THEMES, type Theme } from "@/core/theme";

const colours = (t: Theme): [string, string][] => [...Object.entries(t.C), ...Object.entries(t.TINT)];
const lines = (t: Theme, indent: string) => colours(t).map(([k, v]) => `${indent}--color-${k}: ${v};`).join("\n");

// `light` and `dark` are Uniwind's own variants; the others need declaring for Tailwind to accept `@variant <name>`.
const custom = THEME_NAMES.filter((n) => n !== "light" && n !== "dark");

const css = `/* GENERATED by scripts/theme-css.ts from packages/core/src/theme.ts: do not edit. */
${custom.map((n) => `@custom-variant ${n} (&:where(.${n}, .${n} *));`).join("\n")}

@theme {
${lines(THEMES[DEFAULT_THEME], "  ")}
}

@layer theme {
  :root {
${THEME_NAMES.map((n) => `    @variant ${n} {\n${lines(THEMES[n], "      ")}\n    }`).join("\n\n")}
  }
}
`;

writeFileSync(new URL("../src/theme.css", import.meta.url), css);
