// What the web app's build and the phone's page builds (vite.editor.config.ts, vite.pdf.config.ts) share: the import
// aliases and writing a built page into the app. The palette's CSS variables and the tab's identity are the core's
// (packages/core/vite.ts), the same plugins the site and the extension build with.
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname } from "node:path";
import { fileURLToPath } from "node:url";
import type { Alias, Plugin } from "vite";
import { CORE_SRC } from "../packages/core/vite";

export { identity, theme } from "../packages/core/vite";

export const at = (p: string) => fileURLToPath(new URL(p, import.meta.url));

export const alias: Alias[] = [
  { find: /^@\/core\//, replacement: CORE_SRC },
  { find: /^@\//, replacement: `${at("./src/")}` },
];

/** A built page (`<host>/index.html`) as a string module in the app at `out`: Metro needs no asset extension and the
 *  WebView gets it as `source.html`. Generated and gitignored: with fonts or pdf.js inline it is over 500 KB. */
export function intoApp(o: { host: string; out: string; name: string; script: string }): Plugin {
  let page = "";
  return {
    name: `tefnotes-${o.host}-into-app`,
    configResolved: (c) => { page = `${c.build.outDir}/${o.host}/index.html`; },
    closeBundle() {
      const to = at(o.out), html = readFileSync(page, "utf8");
      mkdirSync(dirname(to), { recursive: true });
      writeFileSync(to, `// GENERATED by web/ \`bun run ${o.script}\` from web/${o.host}: do not edit.\nexport const ${o.name} = ${JSON.stringify(html)};\n`);
    },
  };
}
