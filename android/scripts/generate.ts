// The resources the app takes from the rest of the repository, written at build time (Gradle's `generateTefNotes` task, app/build.gradle.kts)
// into a build folder, never into src/: the default look as colours (packages/core/src/theme.ts through companion.ts's
// DEFAULT_LOOK; the owner's own look comes from the server at run time), the icons as vector drawables (lucide, the
// project's icon set), the brand mark (packages/core/src/brand.ts), plain and as the launcher's foreground, and the brand's
// typeface (assets/fonts).
//   bun scripts/generate.ts <res directory>
import { copyFileSync, mkdirSync, rmSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { fileURLToPath } from "node:url";
import * as lucide from "lucide";
import { MARK_PATH, MARK_VIEWBOX } from "@/core/brand";
import { DEFAULT_LOOK } from "@/core/companion";

const out = process.argv[2];
if (!out) throw new Error("generate: give the res directory to write");

/** The drawables the app names (R.drawable.ic_<key>), each a lucide icon. */
const ICONS = {
  check: "Check", add: "Plus", refresh: "RefreshCw", task: "ListTodo", append: "ListPlus", note: "FilePlus",
  newtask: "ClipboardPlus", page: "Globe", pin: "Pin", box: "Circle", close: "X", fail: "CircleAlert", offline: "CloudOff",
  notes: "NotebookText", picture: "Image", settings: "Settings", lens: "Focus", ask: "Sparkles",
} as const;

type Attrs = Record<string, string | number | undefined>;
const n = (a: Attrs, k: string) => Number(a[k] ?? 0);

/** An SVG shape as path data: a vector drawable draws paths only. */
function pathOf(tag: string, a: Attrs): string {
  switch (tag) {
    case "path": return String(a.d);
    case "line": return `M${n(a, "x1")} ${n(a, "y1")}L${n(a, "x2")} ${n(a, "y2")}`;
    case "polyline": case "polygon": {
      const p = String(a.points).trim().split(/[\s,]+/).map(Number);
      const d = p.reduce((s, v, i) => s + (i % 2 ? ` ${v}` : `${i ? "L" : "M"}${v}`), "");
      return tag === "polygon" ? `${d}Z` : d;
    }
    case "circle": case "ellipse": {
      const rx = n(a, tag === "circle" ? "r" : "rx"), ry = n(a, tag === "circle" ? "r" : "ry"), x = n(a, "cx"), y = n(a, "cy");
      return `M${x - rx} ${y}a${rx} ${ry} 0 1 0 ${2 * rx} 0a${rx} ${ry} 0 1 0 ${-2 * rx} 0Z`;
    }
    case "rect": {
      const x = n(a, "x"), y = n(a, "y"), w = n(a, "width"), h = n(a, "height");
      const rx = Math.min(n(a, a.rx === undefined ? "ry" : "rx"), w / 2), ry = Math.min(n(a, a.ry === undefined ? "rx" : "ry"), h / 2);
      if (!rx || !ry) return `M${x} ${y}h${w}v${h}h${-w}Z`;
      const arc = (dx: number, dy: number) => `a${rx} ${ry} 0 0 1 ${dx} ${dy}`;
      return `M${x + rx} ${y}h${w - 2 * rx}${arc(rx, ry)}v${h - 2 * ry}${arc(-rx, ry)}h${-(w - 2 * rx)}${arc(-rx, -ry)}v${-(h - 2 * ry)}${arc(rx, -ry)}Z`;
    }
    default: throw new Error(`generate: no path for <${tag}>`);
  }
}

const xml = (body: string) => `<?xml version="1.0" encoding="utf-8"?>\n<!-- Generated by android/scripts/generate.ts: never edit. -->\n${body}\n`;

/** A lucide icon: 24 units, strokes only. White, because every use tints it; `stroke` for the one that nothing tints. */
function icon(name: string, stroke = "@android:color/white"): string {
  const nodes = (lucide as unknown as Record<string, [string, Attrs][] | undefined>)[name];
  if (!Array.isArray(nodes)) throw new Error(`generate: lucide has no ${name}`);
  const paths = nodes.map(([tag, a]) =>
    `    <path android:pathData="${pathOf(tag, a)}" android:strokeColor="${stroke}" android:strokeWidth="2" android:strokeLineCap="round" android:strokeLineJoin="round" />`);
  return xml(`<vector xmlns:android="http://schemas.android.com/apk/res/android" android:width="24dp" android:height="24dp" android:viewportWidth="24" android:viewportHeight="24">\n${paths.join("\n")}\n</vector>`);
}

/** The brand mark in `box` (an SVG viewBox of its 1024 canvas), `dp` a side, filled with the colour resource `fill`. */
function mark(box: string, dp: number, fill: string): string {
  const [x, y, w, h] = box.split(" ").map(Number);
  return xml(`<vector xmlns:android="http://schemas.android.com/apk/res/android" android:width="${dp}dp" android:height="${dp}dp" android:viewportWidth="${w}" android:viewportHeight="${h}">
    <group android:translateX="${-x}" android:translateY="${-y}">
        <path android:pathData="${MARK_PATH}" android:fillColor="${fill}" android:fillType="evenOdd" />
    </group>
</vector>`);
}

const { scheme, ...palette } = DEFAULT_LOOK;
const colors = xml(`<resources>\n    <bool name="tf_dark">${scheme === "dark"}</bool>\n${Object.entries(palette).map(([k, v]) => `    <color name="tf_${k}">${v}</color>`).join("\n")}\n</resources>`);

rmSync(out, { recursive: true, force: true });
mkdirSync(join(out, "values"), { recursive: true });
mkdirSync(join(out, "drawable"), { recursive: true });
writeFileSync(join(out, "values", "tf_colors.xml"), colors);
for (const [key, name] of Object.entries(ICONS)) writeFileSync(join(out, "drawable", `ic_${key}.xml`), icon(name));
// The launcher's shortcut: a launcher draws it as it is, so it carries the brand's colour itself.
writeFileSync(join(out, "drawable", "ic_shortcut_newtask.xml"), icon(ICONS.newtask, "@color/tf_brand"));
writeFileSync(join(out, "drawable", "ic_mark.xml"), mark(MARK_VIEWBOX, 24, "@android:color/white"));
// The launcher's foreground is the whole 1024 canvas: the mark sits inside the adaptive icon's safe zone as it is.
writeFileSync(join(out, "drawable", "ic_launcher_foreground.xml"), mark("0 0 1024 1024", 108, "@color/tf_brand"));
writeFileSync(join(out, "drawable", "ic_launcher_monochrome.xml"), mark("0 0 1024 1024", 108, "@android:color/white"));
// The brand's typeface (assets/fonts, OFL), for the app's own screens; a widget is drawn by the launcher in the system's.
mkdirSync(join(out, "font"), { recursive: true });
for (const [weight, name] of [[400, "Regular"], [500, "Medium"], [600, "SemiBold"], [700, "Bold"]] as const)
  copyFileSync(fileURLToPath(new URL(`../../assets/fonts/AtkinsonHyperlegibleNext_${weight}${name}.ttf`, import.meta.url)), join(out, "font", `atkinson_${weight}.ttf`));
