// The resources the app takes from the rest of the repository, written at build time (Gradle's `generateTefNotes` task, app/build.gradle.kts)
// into a build folder, never into src/: the default look as colours (packages/core/src/theme.ts through companion.ts's
// DEFAULT_LOOK; the owner's own look comes from the server at run time), the icons as vector drawables (lucide, the
// project's icon set), the brand mark (packages/core/src/brand.ts), plain and as the launcher's foreground, and the brand's
// typeface (assets/fonts).
// And one Kotlin file, Tokens.kt: the values the web app moves on (Animate UI's motion tokens, the npm package the web
// app reads them from, at the version pinned here) and how long a tick waits (packages/core/src/tick.ts), so a sheet here
// slides, a button presses and a tick lingers as they do there, with no number written twice.
//   bun scripts/generate.ts <res directory> <kotlin directory>
