// The app's icon and the mark every client draws, from the two SVGs here (the logo's one source): `bun assets/icons.ts`
// from the repository root after editing them, with the agent's dependencies installed (its canvas renders the SVG).
// Writes icon.png (the installed web app's icon and the tab's, packages/core/vite.ts) and the mark's outline to
// packages/core/src/brand.ts, the path every brand draws (web/src/components/brand.tsx, site/src/components/ui.tsx, the
// extension's toolbar icon), so each shows the very shape the icon does.
import { createCanvas, loadImage } from "../server/agent/node_modules/@napi-rs/canvas/index.js";
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const here = (name: string) => fileURLToPath(new URL(name, import.meta.url));
const SIZE = 1024;
/** The mark's bounds in the 1024 canvas, padded: the square that frames it as an in-app icon. */
const MARK_BOX = "194 194 636 636";

const canvas = createCanvas(SIZE, SIZE);
canvas.getContext("2d").drawImage(await loadImage(readFileSync(here("logo.svg"))), 0, 0, SIZE, SIZE);
const png = await canvas.encode("png");
if (png.length > 500_000) throw new Error(`icon.png is ${png.length} bytes`);
writeFileSync(here("icon.png"), png);

const path = /<path id="mark"[^>]* d="([^"]+)"/.exec(readFileSync(here("mark.svg"), "utf8"))?.[1];
if (!path) throw new Error("assets/mark.svg has no #mark path");
writeFileSync(
  here("../packages/core/src/brand.ts"),
  `// Generated by assets/icons.ts from assets/mark.svg: never edit.\n` +
    `/** The mark's outline (even-odd) in a 1024 canvas, and the square of it that frames the mark for an in-app icon. */\n` +
    `export const MARK_PATH = "${path}";\nexport const MARK_VIEWBOX = "${MARK_BOX}";\n\n` +
    `/** The mark as a standalone SVG document in \`fill\`: what rasterises it (the extension's toolbar icons). */\n` +
    `export const markSvg = (fill: string) =>\n` +
    `  \`<svg xmlns="http://www.w3.org/2000/svg" viewBox="\${MARK_VIEWBOX}"><path d="\${MARK_PATH}" fill="\${fill}" fill-rule="evenodd"/></svg>\`;\n`,
);
console.log("icons: assets/icon.png and packages/core/src/brand.ts written");
