// Builds lib/core.js, the hooks' copy of the clients' code (core.ts says what is in it), as CommonJS for PocketBase's JS
// VM. Generated, never committed (.gitignore): the image builds it (server/Dockerfile), and so do the integration run
// (server/integration/run.ts) and the hooks' tests (server/bunfig.toml preloads test/core.ts), so both exercise this
// bundle. `bun pb_hooks/bundle/build.ts` from server/ builds it by hand.
//
// goja runs what Bun emits (ES2020+: classes, spread, optional chaining, `\p{..}` with `u`; checked against the pinned
// PocketBase), but has no `URL`: the bundle gets lib/url.js's in its own scope, and nothing else from outside.
import { join } from "node:path";

const here = import.meta.dir;
export const OUT = join(here, "..", "lib", "core.js");

const HEADER = "// Generated by server/pb_hooks/bundle/build.ts from core.ts beside it: never edit, never commit.\n"
  + "var URL = require(\"./url.js\").URL;";

export async function buildCore(): Promise<string> {
  const out = await Bun.build({
    entrypoints: [join(here, "core.ts")], format: "cjs", target: "browser", banner: HEADER,
    outdir: join(here, "..", "lib"), naming: "core.js",
  });
  if (!out.success) throw new AggregateError(out.logs, "The hooks' core bundle did not build");
  const text = await Bun.file(OUT).text();
  const required = [...text.matchAll(/\brequire\(\s*["'`]([^"'`]+)["'`]\s*\)/g)].map((m) => m[1]).filter((p) => p !== "./url.js");
  if (required.length) throw new Error(`The hooks' core bundle requires ${required.join(", ")}: only pure code belongs in it`);
  return OUT;
}

if (import.meta.main) await buildCore();
